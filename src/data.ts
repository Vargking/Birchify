export function createComponent(type: ComponentType): ResumeComponent {
  const catalog = componentCatalog.find((c) => c.type === type)!;
  return {
    id: uid(),
    type,
    title:
      type === "progress"
        ? "新技能"
        : type === "timeline"
          ? "经历名称"
          : type === "tags"
            ? "设计思维, 团队协作, 创意表达"
            : type === "quote"
              ? "保持好奇，持续生长。"
              : type === "links"
                ? "我的作品集"
                : type === "image"
                  ? "作品说明"
                  : "在这里写下你的故事",
    subtitle: type === "timeline" ? "组织 / 学校 · 职位 / 专业" : "",
    description: ["timeline", "project", "text"].includes(type)
      ? "描述你的经历、职责与收获。试着用具体的成果，讲述你的独特价值。"
      : type === "links"
        ? "https://example.com"
        : "",
    date: type === "timeline" ? "2023.09 — 至今" : "",
    value: 85,
    style: catalog.styles[0].value,
    color: "",
    fontSize: 14,
    spacing: 14,
    align: "left",
    bold: false,
    icon: "",
    iconStyle: "line",
    width: 100,
    indent: 0,
  };
}

